/**
 * Bake the built index.html into a CommonJS module the ogPrerender function
 * can require() synchronously.
 *
 * The function serves /event/** and needs the real app shell — the one with
 * this build's hash-busted asset filenames — so it can inject per-climb OG
 * tags and still boot the SPA. Because CI runs `npm run build` and
 * `firebase deploy` from a single checkout, the shell baked here and the
 * shell hosting serves come from the same Rollup output, so the hashes match
 * by construction and nothing needs rewriting.
 *
 * Wired as a `predeploy` hook on the functions target in firebase.json.
 *
 * Usage: node scripts/stage-app-shell.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "dist", "index.html");
const TARGET = join(root, "functions", "appShell.generated.js");

let html;
try {
  html = readFileSync(SOURCE, "utf8");
} catch {
  // Deploying a stale shell means /event/** serves asset paths that 404 —
  // a blank page for every climb link. Refuse rather than guess.
  console.error(
    `stage-app-shell: ${SOURCE} not found.\n` +
      "Run `npm run build` before deploying functions.",
  );
  process.exit(1);
}

if (!html.includes("<!--og-->")) {
  console.error(
    "stage-app-shell: the built index.html has no <!--og--> marker.\n" +
      "ogPrerender replaces that region; without it every climb link would " +
      "fall back to the generic site card.",
  );
  process.exit(1);
}

writeFileSync(
  TARGET,
  "// GENERATED by scripts/stage-app-shell.mjs — do not edit, do not commit.\n" +
    `module.exports = ${JSON.stringify(html)};\n`,
  "utf8",
);

console.log(
  `stage-app-shell: wrote ${TARGET} (${html.length} bytes of app shell)`,
);
